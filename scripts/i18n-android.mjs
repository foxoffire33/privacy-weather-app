#!/usr/bin/env node
// Writes android/app/src/main/res/values-<lang>/strings.xml from the "widgets.android"
// section of each translation, so widget names in Android's widget picker follow the
// system language. English stays in values/strings.xml. Run after editing translations:
//   node scripts/i18n-android.mjs
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const locales = join(root, 'src/i18n/locales');
const res = join(root, 'android/app/src/main/res');
const en = JSON.parse(readFileSync(join(locales, 'en.json'), 'utf8')).widgets.android;
const NAMES = {
  now: 'widget_now', nowDescription: 'widget_now_description',
  timeline: 'widget_timeline', timelineDescription: 'widget_timeline_description',
  thisday: 'widget_thisday', thisdayDescription: 'widget_thisday_description',
  rain: 'widget_rain', rainDescription: 'widget_rain_description',
  hourly: 'widget_hourly', hourlyDescription: 'widget_hourly_description',
};
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/"/g, '\\"');

for (const file of readdirSync(locales).filter((f) => f.endsWith('.json') && f !== 'en.json').sort()) {
  const lang = file.replace('.json', '');
  const tr = JSON.parse(readFileSync(join(locales, file), 'utf8')).widgets?.android ?? {};
  const lines = Object.entries(NAMES).map(([key, name]) => `    <string name="${name}">${esc(tr[key] || en[key])}</string>`);
  const dir = join(res, `values-${lang}`);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'strings.xml'),
    `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/i18n-android.mjs from src/i18n/locales/${file}. Do not edit. -->\n<resources>\n${lines.join('\n')}\n</resources>\n`);
}
console.log('Android widget strings written.');
